import { DataTypes } from "sequelize";
import { sequelize } from "../config/database";
import { PAYEE_TYPE, PAYMENT_METHOD, PAYMENT_STATUS, PAYMENT_TYPE } from "../constants/tableTypes";
import User from "./user.model";
import Client from "./client.model";
import LedgerAccount from "./ledgerAccount.model";
import Location from "./location.model";
import { getNextSequenceNumber } from "../services/sequence.service";
import { SEQUENCE_MODEL } from "../constants/sequenceTypes";

const Payment = sequelize.define(
  "Payment",
  {
    id: {
      type: DataTypes.INTEGER,
      autoIncrement: true,
      primaryKey: true,
    },
    paymentType: {
      type: DataTypes.ENUM(...Object.values(PAYMENT_TYPE)), // incoming = received, outgoing = made
      allowNull: false,
    },
    payeeId: {
      type: DataTypes.INTEGER,
      allowNull: false, // The ID of the entity receiving/sending payment
    },
    payeeType: {
      type: DataTypes.ENUM(...Object.values(PAYEE_TYPE)), // Future-proofing
      allowNull: false,
    },
    amount: {
      type: DataTypes.DECIMAL(15, 2),
      allowNull: false,
    },
    paymentMethod: {
      type: DataTypes.ENUM(...Object.values(PAYMENT_METHOD)),
      allowNull: false,
    },
    clientTransactionNo: {
      type: DataTypes.INTEGER,
      allowNull: true, // not null handled by hook
    },
    transactionCode: {
      type: DataTypes.STRING,
      allowNull: true, // will be generated by hook
    },
    status: {
      type: DataTypes.ENUM(...Object.values(PAYMENT_STATUS)),
      defaultValue: PAYMENT_STATUS.PENDING,
    },
    remark: {
      type: DataTypes.STRING,
      allowNull: true,
    },
    referenceNo: {
      type: DataTypes.STRING,
      allowNull: true,
    },
    referenceDate: {
      type: DataTypes.DATEONLY,
      allowNull: true,
    },
    paymentFor: {
      type: DataTypes.ENUM('ADVANCED_DEPOSIT'),
      allowNull: true
    },
    paymentForId: {
      type: DataTypes.INTEGER,
      allowNull: true
    },
    userId: {
      type: DataTypes.INTEGER,
      references: {
        model: User,
        key: "id",
      },
      onUpdate: "CASCADE",
      onDelete: "RESTRICT",
    },
    clientId: {
      type: DataTypes.INTEGER,
      references: {
        model: Client,
        key: "id",
      },
      onUpdate: "CASCADE",
      onDelete: "RESTRICT",
    },
    accountId: {
      type: DataTypes.INTEGER,
      references: {
        model: LedgerAccount,
        key: "id",
      },
      onUpdate: "CASCADE",
      onDelete: "RESTRICT",
    },
    locationId: {
      type: DataTypes.INTEGER,
      allowNull: false,
      references: {
        model: Location,
        key: "id",
      },
      onDelete: "CASCADE",
      onUpdate: "CASCADE",
    }
  },
  {
    tableName: "payments",
    timestamps: true,
    indexes: [
      {
        unique: true,
        fields: ["clientId", "clientTransactionNo"],
      },
      {
        unique: true,
        fields: ["transactionCode", 'clientId'],
      },
    ],
  }
);

// 🔹 Hook: Auto-Increment `clientTransactionNo` and `transactionCode` using locked sequence
Payment.beforeCreate(async (payment: any, options: any) => {
  if (!payment.clientId) {
    throw new Error("Client ID is required to generate transaction number");
  }

  if (!payment.clientTransactionNo) {
    payment.clientTransactionNo = await getNextSequenceNumber({
      clientId: payment.clientId,
      modelName: SEQUENCE_MODEL.PAYMENT,
      transaction: options?.transaction,
    });
  }

  // Generate transaction code based on Ledger Account name
  if (payment.accountId && !payment.transactionCode) {
    const ledgerAccount: any = await LedgerAccount.findByPk(payment.accountId, {
      transaction: options?.transaction,
    });
    if (ledgerAccount && ledgerAccount.name) {
      // Get first 2-3 characters from the account name
      const accountPrefix = ledgerAccount.name.substring(0, 3).toUpperCase();

      const sequenceNumber = await getNextSequenceNumber({
        clientId: payment.clientId,
        modelName: SEQUENCE_MODEL.PAYMENT_CODE,
        scopeKey: accountPrefix,
        transaction: options?.transaction,
      });

      payment.transactionCode = `${accountPrefix}${sequenceNumber.toString().padStart(3, "0")}`;
    }
  }
});

// Scope configuration for Payment model
(Payment as any).scopeConfig = {
  client: true,
  location: true,
};

export default Payment;



